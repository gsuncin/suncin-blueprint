#!/usr/bin/env bash
# Stamps a mechanical entry into .changelog.md for the staged change set.
#
# This hook records WHICH PATHS CHANGED. It cannot know what the change means —
# that is why every entry it writes is marked "Review required". Replace the
# placeholder before committing; see .claude/skills/changelog-documentation.
set -euo pipefail

CHANGELOG=".changelog.md"

staged="$(git diff --cached --name-only --diff-filter=ACMR \
          | grep -v -e '^\.DS_Store$' -e '^\.changelog\.md$' -e '^README\.md$' || true)"
[ -z "$staged" ] && exit 0

# Already written by hand this commit — leave it alone.
git diff --cached --name-only | grep -qx "$CHANGELOG" && exit 0

# Derive affected areas by path prefix, in a fixed order so the line is stable.
areas=""
# The microservices are DERIVED. A hardcoded `acme-svc-example` here stops
# attributing a changed area the day a second service exists — the same defect,
# in miniature, that this repo removed from the CI matrices and the deploy.
svc_prefixes="$(ls -d acme-svc-*/ 2>/dev/null | sed 's#/$##' | paste -sd' ' -)"
# shellcheck disable=SC2086
for prefix in acme-gateway acme-bff $svc_prefixes acme-web acme-tf \
              .github .claude specs releases scripts; do
    if printf '%s\n' "$staged" | grep -q "^$prefix/"; then
        areas="${areas:+$areas, }$prefix"
    fi
done
printf '%s\n' "$staged" | grep -qv '/' && areas="${areas:+$areas, }root"
[ -z "$areas" ] && areas="root"

file_count="$(printf '%s\n' "$staged" | wc -l | tr -d ' ')"
files="$(printf '%s\n' "$staged" | head -12 | paste -sd', ' -)"
[ "$file_count" -gt 12 ] && files="$files, ..."

[ -f "$CHANGELOG" ] || printf '# Changelog\n' > "$CHANGELOG"
grep -q '^# Changelog' "$CHANGELOG" || {
    printf '# Changelog\n\n%s' "$(cat "$CHANGELOG")" > "$CHANGELOG.tmp"
    mv "$CHANGELOG.tmp" "$CHANGELOG"
}

today="$(date +%Y-%m-%d)"
entry="
## $today

### Pre-Commit Change Review
- Highlight: Captured staged implementation changes before commit.
- Impact: Maintains a traceable implementation register for changed areas.
- Scope: $areas; files: $files
- Verification: Generated by scripts/precommit-changelog-docs.sh from staged paths.
- Docs: Review required. Replace this note with the documentation decision before committing.
"

# NOT `awk -v entry="$entry"`: a literal newline in a -v assignment is an error
# on BSD awk ("awk: newline in string"), so that spelling aborted every commit
# on macOS rather than stamping anything — a hook that fails closed on the
# wrong thing. The entry is read from a file instead, which has no such rule.
entry_file="$(mktemp)"
trap 'rm -f "$entry_file" "$CHANGELOG.tmp"' EXIT
printf '%s\n' "$entry" > "$entry_file"

awk -v entry_file="$entry_file" '
    NR == 1 && /^# Changelog/ {
        print
        while ((getline line < entry_file) > 0) print line
        close(entry_file)
        next
    }
    { print }
' "$CHANGELOG" > "$CHANGELOG.tmp"
mv "$CHANGELOG.tmp" "$CHANGELOG"

git add "$CHANGELOG"
echo "changelog: stamped an entry for [$areas]. Replace the placeholder before you push."
